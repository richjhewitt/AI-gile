def('perms', '🔐 Permissions: ticks follow the rules, save keeps hooks, new folders get the defaults', async (s, ctx) => {
  const local = (() => { try { return JSON.parse(fs.readFileSync(path.join(ROOT, 'aigile.local.json'), 'utf8')).agent || {}; } catch { return {}; } })();
  const folder = path.join(tmp('perms'), 'proj');
  await mkProject(s, 'Alpha', 'ALP');
  check('no folder: refused', (await s.api('GET', '/api/projects/alpha/permissions')).status === 400);
  await s.ok('POST', '/api/projects/alpha/connect', { path: folder, create: true });
  const sfile = path.join(folder, local.settingsFile);
  const r = await s.ok('GET', '/api/projects/alpha/permissions');
  const ways = r.presets.ways.rules.allow[0];
  check('new folder gets run, edit, push-asks and ways', ['Bash', 'Edit', ways].every(x => r.allow.includes(x)) && r.ask.includes('Bash(git push:*)') && !r.allow.includes('WebFetch'), r);
  check('ways rule is an absolute read of the board folder', /^Read\(\/\/[a-z]\/.*\/\*\*\)$/.test(ways), ways);
  const page = await openPage(ctx, '#/p/alpha');
  await page.click('button:has-text("Permissions")');
  await page.waitForSelector('#perm-ticks input');
  const ticked = async k => page.isChecked(`#perm-ticks input[data-k="${k}"]`);
  check('ticks match the file', (await ticked('run')) && (await ticked('ways')) && !(await ticked('web')));
  await page.check('#perm-ticks input[data-k="web"]');
  check('ticking adds the rules', (await page.inputValue('#perm-allow')).includes('WebFetch'));
  await page.uncheck('#perm-ticks input[data-k="run"]');
  check('unticking removes them', !(await page.inputValue('#perm-allow')).split('\n').includes('Bash'));
  await page.fill('#perm-deny', 'Bash(rm -rf:*)');
  await page.click('#dialog button:has-text("Save")');
  await page.waitForSelector('#perm-done:has-text("Saved")');
  const st = JSON.parse(fs.readFileSync(sfile, 'utf8'));
  check('saved to the file', st.permissions.allow.includes('WebFetch') && !st.permissions.allow.includes('Bash') && st.permissions.deny[0] === 'Bash(rm -rf:*)', st.permissions);
  check('hooks kept', !!st.hooks && !!st.hooks.Stop);
  await page.fill('#perm-deny', '');
  await page.click('#dialog button:has-text("Save")');
  await sleep(300);
  check('empty list removed from the file', !('deny' in JSON.parse(fs.readFileSync(sfile, 'utf8')).permissions));
  noErrors(page);
}, true);

def('discover', '🔎 Find my projects: lists folders with git and README, flags copies, imports the ticked ones (AIG-94)', async (s, ctx) => {
  const root = tmp('discover'), g = (cwd, ...a) => spawnSync('git', a, { cwd, encoding: 'utf8' });
  const mk = (name, readme) => { const d = path.join(root, name); fs.mkdirSync(d); if (readme) fs.writeFileSync(path.join(d, 'README.md'), readme); return d; };
  const app = mk('Shop App', '# Shop App\n\nA tiny web shop for **local** makers.\n');
  g(app, 'init', '-q'); g(app, 'add', '.'); g(app, '-c', 'user.name=qa', '-c', 'user.email=qa@x', 'commit', '-qm', 'start');
  mk('Shop App-old'); mk('notes');
  const shopping = mk('Shopping', '# Shopping\n\nLists.\n'); g(shopping, 'init', '-q'); g(shopping, 'add', '.'); g(shopping, '-c', 'user.name=qa', '-c', 'user.email=qa@x', 'commit', '-qm', 'start');
  const found = await s.ok('GET', '/api/discover?dir=' + encodeURIComponent(root));
  const by = n => found.find(f => f.name === n);
  check('git project found with its README line', by('Shop App').git.commits === 1 && by('Shop App').readme === 'A tiny web shop for local makers.' && by('Shop App').suggested, by('Shop App'));
  check('a copy is flagged and not suggested', by('Shop App-old').copy && !by('Shop App-old').suggested);
  check('a plain folder is not suggested', !by('notes').suggested);
  const page = await openPage(ctx, '#/');
  await page.evaluate(d => findProjectsDialog(d), root);
  await page.waitForSelector('.fprow');
  const keys = await page.$$eval('.fprow', rs => rs.map(r => [r.querySelector('.fp-name').value, r.querySelector('.fp-key').value]));
  const ks = keys.filter(k => /^Shop/.test(k[0]) && k[0] !== 'Shop App-old').map(k => k[1]);
  check('two projects starting alike get different keys before Add (AIG-331)', ks.length === 2 && ks[0] !== ks[1] && ks.every(Boolean), keys);
  const own = await page.$eval('.fprow:has(input[value=Shopping]) .fp-key', i => i.value);
  await page.fill('.fprow:has(input[value=Shopping]) .fp-key', ks.find(k => k !== own));
  check('a doubled key is marked at once', await page.$eval('.fprow:has(input[value=Shopping]) .fp-key', i => i.classList.contains('bad')));
  await page.fill('.fprow:has(input[value=Shopping]) .fp-key', own);
  await page.uncheck('#fp-connect');
  await page.click('#dialog button:has-text("Add ticked projects")');
  await page.waitForSelector('#fp-done li');
  const p = (await s.ok('GET', '/api/projects')).find(x => x.name === 'Shop App');
  check('ticked project added with its folder and description', p && p.path.endsWith('/Shop App') && p.description === 'A tiny web shop for local makers.', p);
  const all = await s.ok('GET', '/api/projects');
  check('both suggested ones added with their own keys, no rename', all.length === 2 && new Set(all.map(x => x.key)).size === 2 && all.every(x => ks.includes(x.key)), all.map(x => x.key));
  noErrors(page);
}, true);
